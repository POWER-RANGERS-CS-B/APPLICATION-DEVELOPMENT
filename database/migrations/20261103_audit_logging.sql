-- Additive, rerunnable audit log expansion. Existing audit records are preserved.
CREATE SCHEMA IF NOT EXISTS restaurant;

CREATE TABLE IF NOT EXISTS restaurant.audit_logs (
    log_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER,
    actor_name TEXT,
    action TEXT NOT NULL,
    module TEXT,
    entity_id TEXT,
    previous_values JSONB,
    new_values JSONB,
    details JSONB,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE restaurant.audit_logs
    ADD COLUMN IF NOT EXISTS actor_name TEXT,
    ADD COLUMN IF NOT EXISTS module TEXT,
    ADD COLUMN IF NOT EXISTS entity_id TEXT,
    ADD COLUMN IF NOT EXISTS previous_values JSONB,
    ADD COLUMN IF NOT EXISTS new_values JSONB,
    ADD COLUMN IF NOT EXISTS details JSONB;

CREATE INDEX IF NOT EXISTS audit_logs_created_at_idx
    ON restaurant.audit_logs (created_at DESC, log_id DESC);

CREATE INDEX IF NOT EXISTS audit_logs_module_created_at_idx
    ON restaurant.audit_logs (module, created_at DESC);

CREATE INDEX IF NOT EXISTS audit_logs_user_created_at_idx
    ON restaurant.audit_logs (user_id, created_at DESC);
