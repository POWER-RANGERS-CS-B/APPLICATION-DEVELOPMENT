BEGIN;

ALTER TABLE restaurant.users
    ADD COLUMN IF NOT EXISTS preferred_theme TEXT NOT NULL DEFAULT 'light';

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conrelid = 'restaurant.users'::regclass
          AND conname = 'users_preferred_theme_check'
    ) THEN
        ALTER TABLE restaurant.users
            ADD CONSTRAINT users_preferred_theme_check
            CHECK (preferred_theme IN ('light', 'dark'));
    END IF;
END
$$;

CREATE TABLE IF NOT EXISTS restaurant.customer_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES restaurant.users(id) ON DELETE CASCADE,
    reservation_id INTEGER REFERENCES restaurant.reservations(id) ON DELETE SET NULL,
    notification_type TEXT NOT NULL,
    title TEXT NOT NULL,
    message TEXT NOT NULL,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at TIMESTAMP WITHOUT TIME ZONE
);

CREATE INDEX IF NOT EXISTS customer_notifications_unread_idx
    ON restaurant.customer_notifications (user_id, created_at DESC)
    WHERE read_at IS NULL;

CREATE INDEX IF NOT EXISTS customer_notifications_history_idx
    ON restaurant.customer_notifications (user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS restaurant.revoked_auth_tokens (
    token_id TEXT PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES restaurant.users(id) ON DELETE CASCADE,
    expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS revoked_auth_tokens_expiry_idx
    ON restaurant.revoked_auth_tokens (expires_at);

COMMIT;
