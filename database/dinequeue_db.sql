-- Dine-ari PostgreSQL schema for a fresh dinequeue_db database.
-- Connect to dinequeue_db before running this file. This file intentionally
-- does not CREATE/DROP a database, insert seed data, or alter existing data.
-- Schema contract verified against the current backend models and migrations.

BEGIN;

CREATE SCHEMA restaurant;
SET LOCAL search_path TO restaurant, public;

-- Authenticated admin/staff accounts only. Customers use guest flows and have
-- no account or password. Passwords are bcrypt hashes written by the backend.
CREATE TABLE restaurant.users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    username TEXT NOT NULL,
    email TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('staff', 'admin')),
    deleted_at TIMESTAMP WITHOUT TIME ZONE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX users_username_lower_unique_idx
    ON restaurant.users (lower(username));

CREATE UNIQUE INDEX users_email_lower_unique_idx
    ON restaurant.users (lower(email));

-- Floor-plan tables and their current operational status.
CREATE TABLE restaurant.restaurant_tables (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name TEXT NOT NULL,
    position_x INTEGER,
    position_y INTEGER,
    status TEXT NOT NULL DEFAULT 'vacant'
        CHECK (status IN ('vacant', 'reserved', 'locked', 'occupied')),
    deleted_at TIMESTAMP WITHOUT TIME ZONE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE restaurant.chairs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_id INTEGER NOT NULL
        REFERENCES restaurant.restaurant_tables (id) ON DELETE CASCADE,
    chair_label TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'vacant'
        CHECK (status IN ('vacant', 'reserved', 'occupied')),
    locked_until TIMESTAMP WITHOUT TIME ZONE,
    deleted_at TIMESTAMP WITHOUT TIME ZONE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- A reservation stores customer details as well as optional links to an
-- account and a floor-plan table, matching the guest checkout flow.
CREATE TABLE restaurant.reservations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER REFERENCES restaurant.users (id) ON DELETE SET NULL,
    table_id INTEGER REFERENCES restaurant.restaurant_tables (id) ON DELETE SET NULL,
    num_guests INTEGER NOT NULL CHECK (num_guests > 0),
    status TEXT NOT NULL DEFAULT 'active'
        CHECK (status IN (
            'active', 'completed', 'confirmed', 'cancelled', 'canceled', 'rejected'
        )),
    reservation_date DATE NOT NULL,
    reservation_time TIME NOT NULL,
    customer_name TEXT NOT NULL,
    contact_number TEXT NOT NULL,
    reservation_code TEXT UNIQUE,
    qr_code TEXT,
    reservation_token TEXT,
    deleted_at TIMESTAMP WITHOUT TIME ZONE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Menu categories and inventory are stored directly on menu_items in the
-- current application; stock_count is the inventory quantity.
CREATE TABLE restaurant.menu_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_name TEXT NOT NULL,
    category TEXT NOT NULL,
    price NUMERIC(10, 2) NOT NULL CHECK (price >= 0),
    stock_count INTEGER NOT NULL DEFAULT 0 CHECK (stock_count >= 0),
    description TEXT,
    image_url TEXT,
    deleted_at TIMESTAMP WITHOUT TIME ZONE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Payment method and status are part of the order record in the current
-- workflow. GCash and Card are the methods supported by the backend.
CREATE TABLE restaurant.orders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_code TEXT NOT NULL UNIQUE,
    user_id INTEGER REFERENCES restaurant.users (id) ON DELETE SET NULL,
    reservation_id INTEGER REFERENCES restaurant.reservations (id) ON DELETE SET NULL,
    type TEXT NOT NULL CHECK (type IN ('dine_in', 'takeout')),
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'preparing', 'ready', 'completed')),
    payment_status TEXT NOT NULL DEFAULT 'unpaid',
    payment_method TEXT NOT NULL DEFAULT 'GCash'
        CHECK (payment_method IN ('GCash', 'Card')),
    total_amount NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
    customer_name TEXT,
    contact_number TEXT,
    qr_code TEXT,
    receipt_token TEXT,
    deleted_at TIMESTAMP WITHOUT TIME ZONE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE restaurant.order_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL REFERENCES restaurant.orders (id),
    menu_item_id INTEGER NOT NULL REFERENCES restaurant.menu_items (id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(10, 2) NOT NULL CHECK (unit_price >= 0),
    subtotal NUMERIC(10, 2) NOT NULL CHECK (subtotal >= 0),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    deleted_at TIMESTAMP WITHOUT TIME ZONE
);

-- Completed-order history stores the customer and line-item summary as a
-- snapshot; order_id becomes NULL if an order is later removed.
CREATE TABLE restaurant.order_history (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER REFERENCES restaurant.orders (id) ON DELETE SET NULL,
    order_code TEXT NOT NULL,
    customer_name TEXT NOT NULL,
    customer_email TEXT NOT NULL,
    order_type TEXT NOT NULL CHECK (order_type IN ('dine_in', 'takeout')),
    payment_method TEXT NOT NULL,
    payment_status TEXT NOT NULL,
    total_amount NUMERIC(10, 2) NOT NULL CHECK (total_amount >= 0),
    ordered_items TEXT NOT NULL DEFAULT '',
    completed_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Audit entries deliberately retain historical actor text and JSON snapshots
-- if the associated account is removed.
CREATE TABLE restaurant.audit_logs (
    log_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER REFERENCES restaurant.users (id) ON DELETE SET NULL,
    actor_name TEXT,
    action TEXT NOT NULL,
    module TEXT,
    entity_id TEXT,
    previous_values JSONB,
    new_values JSONB,
    details JSONB,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Indexes supporting the backend's active-record listing, joins, and history.
CREATE INDEX chairs_table_id_active_idx
    ON restaurant.chairs (table_id)
    WHERE deleted_at IS NULL;

CREATE INDEX reservations_table_id_idx
    ON restaurant.reservations (table_id);

CREATE INDEX reservations_user_id_idx
    ON restaurant.reservations (user_id);

CREATE INDEX reservations_date_status_active_idx
    ON restaurant.reservations (reservation_date, status)
    WHERE deleted_at IS NULL;

CREATE INDEX menu_items_category_active_idx
    ON restaurant.menu_items (category, item_name)
    WHERE deleted_at IS NULL;

CREATE INDEX orders_status_created_active_idx
    ON restaurant.orders (status, created_at DESC)
    WHERE deleted_at IS NULL;

CREATE INDEX orders_user_id_idx
    ON restaurant.orders (user_id);

CREATE INDEX orders_reservation_id_idx
    ON restaurant.orders (reservation_id);

CREATE INDEX order_items_order_id_idx
    ON restaurant.order_items (order_id);

CREATE INDEX order_items_menu_item_id_idx
    ON restaurant.order_items (menu_item_id);

CREATE INDEX order_history_order_id_idx
    ON restaurant.order_history (order_id);

CREATE INDEX order_history_completed_at_idx
    ON restaurant.order_history (completed_at DESC);

CREATE INDEX audit_logs_created_at_idx
    ON restaurant.audit_logs (created_at DESC, log_id DESC);

CREATE INDEX audit_logs_module_created_at_idx
    ON restaurant.audit_logs (module, created_at DESC);

CREATE INDEX audit_logs_user_created_at_idx
    ON restaurant.audit_logs (user_id, created_at DESC);

COMMIT;
